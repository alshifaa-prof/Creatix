export function getStoredMockData(): MockDatabase {
  if (typeof window === 'undefined') return INITIAL_MOCK_DATA;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_MOCK_DATA));
      return INITIAL_MOCK_DATA;
    }
    return JSON.parse(raw) as MockDatabase;
  } catch (e) {
    console.error('Failed to load mock data from localStorage, falling back to initial', e);
    return INITIAL_MOCK_DATA;
  }
}

export function saveStoredMockData(data: MockDatabase): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
  } catch (e) {
    console.error('Failed to save mock data to localStorage', e);
  }
}
